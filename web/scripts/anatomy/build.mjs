import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { bench, station, water, band, gateway } from "./assemblies.mjs";
import { k, A, P, R, at, partsCount } from "./parts.mjs";

bench(); station(); water(); band(); gateway();
A.settle(R, P);
const art = R.items.toSorted((a,b)=>a.key-b.key).map(item=>item.svg).join("");
const anchors = {
  station: at([-106,3,28]), water: at([13,45,8]),
  band: at([104,42.5,60.5]), gateway: at([96,-35,20]),
};
function crop(plan, top) {
 const points=k.boxCorners(plan,0,top).map(point=>at(point));
 const xs=points.map(point=>point[0]),ys=points.map(point=>point[1]);
 const cx=(Math.min(...xs)+Math.max(...xs))/2,cy=(Math.min(...ys)+Math.max(...ys))/2;
 const height=Math.max(Math.max(...ys)-Math.min(...ys)+60,(Math.max(...xs)-Math.min(...xs)+60)*.6);
 return [cx-height/1.2,cy-height/2,height/.6,height];
}
const focus = {
 all:[0,0,900,540],
 station:crop({x:-151,y:-70,w:78,d:87},123),
 water:crop({x:-46,y:2,w:66,d:56},90),
 band:crop({x:80,y:6,w:48,d:56},61),
 gateway:crop({x:67,y:-71,w:68,d:40},50),
};
const surfaces = {
 rfid: { transform:k.topMatrix([5,22],8.95,P), width:16, height:22 },
 band: { transform:k.topMatrix([94,28],60.6,P), width:20, height:11 },
 station: { transform:k.topMatrix([-131,-8],27,P), width:23, height:8 },
};
const generated = `// Generated by scripts/anatomy/build.mjs. MIT Anatomy geometry; do not hand edit.\nexport const DEVICE_ART = ${JSON.stringify(art)}\n`;
writeFileSync(resolve("src/components/figures/terma/generated-art.ts"), generated);
writeFileSync(resolve("src/components/figures/terma/generated-view.ts"), `// Generated by scripts/anatomy/build.mjs.\nexport const DEVICE_ANCHORS = ${JSON.stringify(anchors)} as const\nexport const DEVICE_FOCUS = ${JSON.stringify(focus)} as const\nexport const DEVICE_PARTS = ${partsCount()}\nexport const DEVICE_SURFACES = ${JSON.stringify(surfaces)} as const\n`);
console.log(`TERMA figure: ${partsCount()} solids; ${(art.length/1024).toFixed(0)} KiB static SVG`);
A.auditOrExit(R,P);
